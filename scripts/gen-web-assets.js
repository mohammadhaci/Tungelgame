// Regenerates src/ui/assets-b64.ts: base64 data URIs of assets/img/* for the
// web build (assets.web.ts), so the exported game works as one HTML file.
// Run after changing any image: node scripts/gen-web-assets.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'img');
const out = path.join(__dirname, '..', 'src', 'ui', 'assets-b64.ts');

const mime = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg' };
const entries = fs
  .readdirSync(dir)
  .filter((f) => mime[path.extname(f)])
  .map((f) => {
    const b64 = fs.readFileSync(path.join(dir, f)).toString('base64');
    const key = path.basename(f, path.extname(f));
    return `  '${key}': 'data:${mime[path.extname(f)]};base64,${b64}',`;
  });

fs.writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-web-assets.js — do not edit by hand.\n` +
    `export const B64: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`wrote ${out} (${entries.length} images)`);
